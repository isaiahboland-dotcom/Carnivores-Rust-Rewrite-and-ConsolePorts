//! The behaviour script in the original engine (`run --engine original`
//! with `behaviours.toml`): one hunt with every scenario animal picked in
//! the menu. The hunter walks and runs (W held, Shift toggling run), the
//! first living animal of each AI is alarmed, then each is slain, and the
//! hook logs the watched one every frame (`original/behave.c`). The checks
//! are our engine's (`c2_core::scenario::Subject::verdicts`), on those
//! logged poses, so `compare ORIGINAL OURS` can set the speeds and clips
//! side by side (`behaviour_parity`).

use std::fmt::Write as _;
use std::path::Path;
use std::time::Duration;

use anyhow::{bail, Context, Result};
use c2_core::scenario::{
    layout, stage_names, BehaviourPlan, Layout, Sample, SpeciesRef, Subject, Track,
};
use serde_json::{json, Value};

use super::addrs::Addrs;
