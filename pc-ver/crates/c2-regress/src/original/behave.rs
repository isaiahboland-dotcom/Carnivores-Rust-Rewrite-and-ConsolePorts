/// Our ticks per original frame.
const TICKS_PER_FRAME: u32 = FRAME_MS / c2_core::scenario::TICK_MS as u32;
/// Frames between stages: the hunter coasts to a stop after a walk.
const GAP: u32 = 30;

/// One stage's watch: the frames whose samples it judges.
#[derive(Debug, Clone, PartialEq)]
struct Window {
    stage: String,
    subject: Subject,
    /// The animal's AI (none for the hunter).
    ai: Option<i32>,
    start: u32,
    end: u32,
}

struct BehaveScript {
    text: String,
    shots: Vec<(String, u32)>,
    windows: Vec<Window>,
    exit_frame: u32,
}

/// `PlayerAlpha`, when the hunter's position globals lie as the shipped
/// renderers have them (`PlayerX`, `PlayerY`, `PlayerZ` 4 bytes apart,
/// downwards): the next one down. The hook checks it against
/// `CameraAlpha` before writing it.
fn player_alpha(a: &Addrs) -> Option<u32> {
    let [x, y, z] = a.player;
    (y.wrapping_add(4) == x && z.wrapping_add(4) == y).then(|| z.wrapping_sub(4))
}

/// Where our engine's scenario puts things, for the original: the
/// hunter's `place` line and each animal's spot.
struct Spots {
    place: String,
    animals: Vec<[i32; 2]>,
}

impl Spots {
    fn new(l: &Layout, yaw: f32) -> Self {
        let [x, y, z] = l.player;
        Self {
            place: format!(
                "place {} {} {} {}",
                x as i32,
                y as i32,
                z as i32,
                (yaw * 1000.0) as i32
            ),
            animals: l
                .animals
                .iter()
                .map(|a| [a[0] as i32, a[1] as i32])
                .collect(),
        }
    }
}

fn behave_script(
    addrs: &Addrs,
    b: &BehaviourPlan,
    warm: u32,
    names: &[String],
    ais: &[i32],
    spots: &Spots,
) -> BehaveScript {
    let k = c2_core::profile::default_keys();
    let (fwd, run) = (vk(k.forward), vk(k.run));
    let mut text = String::from("# generated by c2-regress: behaviours in the original engine\n");
    text.push_str(&addrs.script_lines());
    if let Some(a) = player_alpha(addrs) {
        let _ = writeln!(text, "0 addr player_alpha {a:#x}");
    }
    // On our engine's landing, looking along its yaw, before the warm-up
    // picture and again before each walk.
    let _ = writeln!(text, "10 {}\n10 pacify", spots.place);
    let mut t = warm;
    let mut shots = vec![("warmup".to_string(), t)];
    let _ = writeln!(text, "{t} shot warmup");
    let mut windows = Vec::new();
    for (stage, subject) in stage_names(names) {
        t += 10;
        let _ = writeln!(text, "{t} mark {stage}");
        let start = t;
        let (ai, len) = match subject {
            Subject::Hunter { run: running } => {
                let len = b.move_ticks / TICKS_PER_FRAME;
                let _ = writeln!(text, "{t} {}\n{t} track hunter", spots.place);
                if running {
                    // The run key toggles run mode (`ToggleRunMode`).
                    let _ = writeln!(text, "{t} tap {run}\n{} tap {run}", t + len + 1);
                }
                let _ = writeln!(text, "{t} key {fwd} down\n{} key {fwd} up", t + len);
                (None, len)
            }
            Subject::Runner(n) => {
                let [x, z] = spots.animals[n];
                let _ = writeln!(text, "{t} alarm {} {x} {z}", ais[n]);
                (Some(ais[n]), b.run_ticks / TICKS_PER_FRAME)
            }
            Subject::Dying(n) => {
                let [x, z] = spots.animals[n];
                let _ = writeln!(text, "{t} slay {} {x} {z}", ais[n]);
                (Some(ais[n]), b.die_ticks / TICKS_PER_FRAME)
            }
        };
        t += len;
        let _ = writeln!(text, "{t} shot {stage}\n{t} untrack");
        shots.push((stage.clone(), t));
        windows.push(Window {
            stage,
            subject,
            ai,
            start,
            end: t,
        });
        if matches!(subject, Subject::Hunter { .. }) {
            t += GAP;
        }
    }
    t += 10;
    let _ = writeln!(text, "{t} shot end\n{} exit", t + 1);
    shots.push(("end".into(), t));
    BehaveScript {
        text,
        shots,
        windows,
        exit_frame: t + 1,
    }
}

/// What the hook logged.
#[derive(Debug, Default, PartialEq)]
struct BehaveLog {
    /// `(frame, AI, found)` for each alarm and slay.
    picks: Vec<(u32, i32, bool)>,
    /// `(frame, sample)`.
    samples: Vec<(u32, Sample)>,
    near: Vec<u32>,
    /// When the hunter died (the original ends the hunt 12 s later).
    dead: Option<u32>,
}

fn parse_log(log: &str) -> BehaveLog {
    let mut out = BehaveLog::default();
    for line in log.lines() {
        let w: Vec<&str> = line.split_whitespace().collect();
        let Some(f) = (w.first() == Some(&"frame"))
            .then(|| w.get(1).and_then(|f| f.parse().ok()))
            .flatten()
        else {
            continue;
        };
        match w.get(2) {
            Some(&("alarm" | "slay")) if w.len() >= 6 => {
                let ai = w[4].parse().unwrap_or(-1);
                out.picks.push((f, ai, w[5] == "index"));
            }
            Some(&"track") if w.len() >= 11 => {
                let n: Vec<i64> = w[3..11].iter().filter_map(|v| v.parse().ok()).collect();
                if n.len() == 8 {
                    out.samples.push((
                        f,
                        Sample {
                            at: [n[3] as f32, n[4] as f32],
                            phase: n[1].max(0) as usize,
                            ftime: n[2] as i32,
                            scale: n[7] as f32 / 1000.0,
                        },
                    ));
                }
            }
            Some(&"near") => out.near.push(f),
            Some(&"hunter") if w.get(3) == Some(&"dead") => out.dead = Some(f),
            _ => {}
        }
    }
    out
}

/// A stage judged as our engine judges its own.
struct Judged {
    passed: bool,
    why: String,
    events: Vec<Value>,
    report: Option<Value>,
}

fn judge(b: &BehaviourPlan, w: &Window, log: &BehaveLog) -> Judged {
    let mut events = Vec::new();
    let mut verify = |name: &str, ok: bool, detail: String| {
        events.push(event(w.end, "verify", &w.stage, name, Some(ok), &detail));
        (ok, format!("{name}: {detail}"))
    };
    if let Some(d) = log.dead.filter(|&d| d <= w.end) {
        let (_, why) = verify(
            "hunter_alive",
            false,
            format!("an animal killed the hunter at frame {d}"),
        );
        return Judged {
            passed: false,
            why,
            events,
            report: None,
        };
    }
    let picked = log.picks.iter().find(|p| p.0 == w.start);
    if let (Some(ai), false) = (w.ai, picked.is_some_and(|p| p.2)) {
        let (_, why) = verify(
            "animal_found",
            false,
            format!("no living animal of AI {ai} in the hunt"),
        );
        return Judged {
            passed: false,
            why,
            events,
            report: None,
        };
    }
    // A runner's watch ends where the hook calmed it near the hunter.
    let end = log
        .near
        .iter()
        .copied()
        .find(|&f| f >= w.start && f <= w.end)
        .unwrap_or(w.end);
    let mut track = Track::new(FRAME_MS);
    track.samples.extend(
        log.samples
            .iter()
            .filter(|(f, _)| *f >= w.start && *f <= end)
            .map(|(_, s)| *s),
    );
    let (mut all, mut first) = (true, None);
    for (name, ok, detail) in w.subject.verdicts(&track, b) {
        let (ok, why) = verify(name, ok, format!("{detail} (frames of {FRAME_MS} ms)"));
        if !ok && all {
            first = Some(why);
        }
        all &= ok;
    }
    let report = w.subject.report(&w.stage, &track, b);
    Judged {
        passed: all,
        why: first.unwrap_or_default(),
        events,
        report: Some(crate::behaviour_parity::report_json(&report)),
    }
}

/// Runs the hunt `repeat` times into `dir`; returns whether every stage
/// passed.
pub fn run(o: &Original, dir: &Path, b: &BehaviourPlan, area: &str) -> Result<bool> {
    let mut ais = Vec::new();
    let mut names = Vec::new();
    for r in &o.scenario.species {
        let SpeciesRef::Ai(a) = r else {
            bail!("the original's menu takes hunt animals by AI number, not {r:?}");
        };
        ais.push(*a);
        names.push(
            o.game
                .species
                .iter()
                .find(|sp| sp.info.ai == *a)
                .map_or_else(|| format!("ai {a}"), |sp| sp.info.name.clone()),
        );
    }
    let weapons = o.game.weapon_names();
    let args = script::command_line(area, o.scenario, weapons.len(), &|_| None)?;
    let game_dir = wine::game_copy(o.game_dir, o.work, &o.game.content_hash)?;
    let prefix = wine::prefix(o.work)?;
    let exe = wine::find_ci(&game_dir, "v_soft.ren")
        .context("no v_soft.ren (the software-rendered hunt) in the game folder")?;
    let addrs = Addrs::scan(&std::fs::read(&exe)?)
        .with_context(|| format!("finding the hunt's globals in {}", exe.display()))?;
    let warm = (o.scenario.warmup_ticks / TICKS_PER_FRAME).max(1);
    let l = layout(&o.game.area, o.scenario).map_err(|e| anyhow::anyhow!("{e}"))?;
    let s = behave_script(
        &addrs,
        b,
        warm,
        &names,
        &ais,
        &Spots::new(&l, o.scenario.yaw),
    );
    let script_path = dir.join("original-script.txt");
    std::fs::write(&script_path, &s.text)?;
    let shots_dir = dir.join("screenshots");
    std::fs::create_dir_all(&shots_dir)?;

    let mut log_all = format!("globals: {addrs:#x?}\n");
    let mut runs: Vec<(Vec<String>, BehaveLog)> = Vec::new();
    let mut timeouts = 0;
    for rep in 0..o.repeat.max(1) {
        let (code, hook_log) = wine::run_fresh(&wine::Launch {
            prefix: &prefix,
            hook_dir: o.hook_dir,
            game_dir: &game_dir,
            exe: &exe,
            args: &args,
            script: &script_path,
            exit_frame: s.exit_frame,
            timeout: Duration::from_secs(300),
        })?;
        timeouts += usize::from(code.is_none());
        log_all.push_str(&format!("--- run {} (exit {code:?})\n{hook_log}", rep + 1));
        let hashes = s
            .shots
            .iter()
            .map(|(f, _)| sha_file(&game_dir.join(format!("{f}.bmp"))))
            .collect();
        if rep == 0 {
            for (f, _) in &s.shots {
                if let Ok(img) = load_bmp(&game_dir.join(format!("{f}.bmp"))) {
                    let png = crate::image_diff::encode_rgb(img.width, img.height, &img.rgb)?;
                    std::fs::write(shots_dir.join(format!("{f}.png")), png)?;
                }
            }
        }
        runs.push((hashes, parse_log(&hook_log)));
    }
    let identical = runs.iter().all(|r| r == &runs[0]);
    let log = &runs[0].1;

    let warm_ok = load_bmp(&shots_dir.join("warmup.png"))
        .or_else(|_| load_bmp(&game_dir.join("warmup.bmp")))
        .is_ok_and(|w| (w.width, w.height) == (800, 600));
    let mut stages = vec![stage(
        "warmup",
        if warm_ok { "passed" } else { "failed" },
        if warm_ok {
            String::new()
        } else {
            "no 800x600 warm-up picture".into()
        },
        warm,
    )];
    let (mut events, mut details) = (Vec::new(), Vec::new());
    for w in &s.windows {
        let j = judge(b, w, log);
        events.extend(j.events);
        details.extend(j.report);
        let status = if j.passed { "passed" } else { "failed" };
        stages.push(stage(&w.stage, status, j.why, w.end));
    }
    for st in &stages {
        events.push(event(
            st["end_tick"].as_u64().unwrap_or(0) as u32,
            "stage_end",
            st["name"].as_str().unwrap_or(""),
            st["status"].as_str().unwrap_or(""),
            Some(st["status"] != "failed"),
            st["reason"].as_str().unwrap_or(""),
        ));
    }
    let checkpoints: Vec<Value> = s
        .shots
        .iter()
        .zip(&runs[0].0)
        .map(|((f, frame), h)| json!({ "name": f, "frame": frame, "screenshot_sha256": h }))
        .collect();
    let count = |key: &str| stages.iter().filter(|st| st["status"] == key).count();
    let failed = count("failed") > 0 || (o.repeat > 1 && !identical) || timeouts > 0;
    let why_none = "the original's simulation is not timed; its clock is virtual (20 ms a frame)";
    let metrics = json!({
        "result": if failed { "failed" } else { "passed" },
        "engine": "original",
        "functional": {
            "map": o.game.area_name,
            "animals_expected": o.scenario.species.len(),
            "animals_placed": unavailable("the original places its own animals; the first of each AI is watched"),
            "animals_end": unavailable("not read"),
            "animals_end_expected": 0,
            "weapon_registry": o.game.weapons.len(),
            "weapon_registry_expected": o.def.weapons,
            "weapons_fired_once": 0,
            "weapons_to_fire": 0,
            "behaviours_detail": details,
            "stages": { "passed": count("passed"), "failed": count("failed"), "unsupported": 0 },
            "timeouts": timeouts,
            "panics": 0,
            "setup_error": Value::Null,
        },
        "ui": {},
        "simulation": unavailable(why_none),
        "render": unavailable(why_none),
        "memory": { "process_bytes": unavailable(why_none), "peak_bytes": unavailable(why_none) },
        "determinism": if o.repeat < 2 {
            json!({ "repeats": 1, "identical": unavailable("one run: use --repeat 2 or more") })
        } else {
            json!({ "repeats": o.repeat, "identical": identical,
                    "compared": "every screenshot byte for byte, and every logged pose" })
        },
        "checkpoints": checkpoints,
    });
    let mut man = manifest(o, &args, &exe, o.repeat.max(1));
    man["original"]["hook"] = json!(
        "c2hook.dll: virtual timeGetTime, scripted input, growable heap, presented-frame capture; \
         behave.c alarms and slays the watched animal and logs it every frame"
    );
    write_json(&dir.join("metrics.json"), &metrics)?;
    write_json(&dir.join("manifest.json"), &man)?;
    write_jsonl(&dir.join("events.jsonl"), &events)?;
    std::fs::write(dir.join("engine.log"), log_all)?;
    Ok(!failed)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn plan() -> BehaviourPlan {
        BehaviourPlan {
            move_ticks: 300,
            measure_ticks: 150,
            walk_speed: 300.0,
            run_speed: 700.0,
            speed_tolerance: 0.05,
            run_ticks: 1000,
            min_run_speed: 400.0,
            die_ticks: 400,
            min_moving_ticks: 20,
            hold_ticks: 50,
            max_drift: 256.0,
        }
    }

    fn addrs() -> Addrs {
        Addrs {
            health: 1,
            characters: 2,
            count: 3,
            player: [4, 5, 6],
            camera_alpha: 7,
        }
    }

    #[test]
    fn the_script_walks_runs_alarms_and_slays() {
        let spots = Spots::new(
            &Layout {
                player: [1000.5, 50.0, 2000.0],
                animals: vec![[3000.0, -40.7]],
            },
            0.5,
        );
        let s = behave_script(&addrs(), &plan(), 100, &["T-Rex".into()], &[18], &spots);
        let w: Vec<(&str, u32, u32)> = s
            .windows
            .iter()
            .map(|w| (w.stage.as_str(), w.start, w.end))
            .collect();
        assert_eq!(
            w,
            [
                ("hunter_walk", 110, 260),
                ("hunter_run", 300, 450),
                ("run_01_t_rex", 490, 990),
                ("die_01_t_rex", 1000, 1200)
            ]
        );
        for line in [
            "10 place 1000 50 2000 500\n10 pacify\n",
            "110 place 1000 50 2000 500\n110 track hunter\n110 key W down\n260 key W up\n260 shot hunter_walk\n260 untrack\n",
            "300 tap SHIFT\n451 tap SHIFT\n300 key W down\n450 key W up\n",
            "490 alarm 18 3000 -40\n990 shot run_01_t_rex\n990 untrack\n",
            "1000 slay 18 3000 -40\n",
            "1210 shot end\n1211 exit\n",
        ] {
            assert!(s.text.contains(line), "{line}\n---\n{}", s.text);
        }
        assert_eq!(s.exit_frame, 1211);
        assert!(!s.text.contains("player_alpha"), "not 4 bytes apart");
        let near = Addrs {
            player: [0x88, 0x84, 0x80],
            ..addrs()
        };
        assert_eq!(player_alpha(&near), Some(0x7c));
        assert_eq!(s.shots.first().map(|x| x.1), Some(100));
    }

    #[test]
    fn the_hooks_log_is_read_and_judged() {
        let mut log = String::from("frame 110 mark hunter_walk\n");
        // 300 units/s: 6 units a 20 ms frame.
        for f in 110..=260 {
            let x = (f - 110) * 6;
            log.push_str(&format!("frame {f} track -1 0 0 {x} 0 {x} 0 1000\n"));
        }
        log.push_str("frame 490 alarm AI 18 index 7\nframe 495 track 7 2 0 0 0 0 0 863\n");
        log.push_str("frame 496 near\nframe 1000 slay AI 13 not found\nframe 1300 hunter dead\n");
        let l = parse_log(&log);
        assert_eq!(l.picks, [(490, 18, true), (1000, 13, false)]);
        assert_eq!((l.near.as_slice(), l.dead), (&[496][..], Some(1300)));
        assert!((l.samples.last().unwrap().1.scale - 0.863).abs() < 1e-6);
        let p = plan();
        let walk = Window {
            stage: "hunter_walk".into(),
            subject: Subject::Hunter { run: false },
            ai: None,
            start: 110,
            end: 260,
        };
        let j = judge(&p, &walk, &l);
        assert!(j.passed, "{}", j.why);
        assert_eq!(j.report.unwrap()["speed"], 300.0);
        let dying = Window {
            stage: "die_01".into(),
            subject: Subject::Dying(0),
            ai: Some(13),
            start: 1000,
            end: 1200,
        };
        let j = judge(&p, &dying, &l);
        assert!(!j.passed && j.why.contains("animal_found"), "{}", j.why);
        let late = Window {
            start: 1400,
            end: 1600,
            ..dying
        };
        let j = judge(&p, &late, &l);
        assert!(!j.passed && j.why.contains("hunter_alive"), "{}", j.why);
    }
}
