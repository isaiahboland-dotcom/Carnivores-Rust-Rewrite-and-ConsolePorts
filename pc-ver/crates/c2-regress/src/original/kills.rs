/// Our ticks per original frame.
const TICKS_PER_FRAME: u32 = FRAME_MS / c2_core::scenario::TICK_MS as u32;

/// One killer's hunt script, and its screenshots' names.
struct KillScript {
    stage: String,
    ai: i32,
    text: String,
    shots: Vec<(String, u32)>,
    exit_frame: u32,
}

fn kill_script(
    addrs: &Addrs,
    k: &KillPlan,
    warm: u32,
    n: usize,
    ai: i32,
    name: &str,
) -> KillScript {
    let stage = format!("kill_{:02}_{}", n + 1, slug(name));
    let (mid, late) = (
        k.mid_ticks / TICKS_PER_FRAME,
        (k.mid_ticks + k.late_ticks) / TICKS_PER_FRAME,
    );
    let release = warm + 1;
    let exit_frame = release + k.timeout_ticks / TICKS_PER_FRAME + late + 10;
    let mut text = String::from("# generated by c2-regress: a kill in the original engine\n");
    text.push_str(&addrs.script_lines());
    let mut shots = Vec::new();
    if n == 0 {
        text.push_str(&format!("{warm} shot warmup\n"));
        shots.push(("warmup".to_string(), warm));
    }
    text.push_str(&format!(
        "{release} mark {stage}\n{release} release {ai} {}\n",
        k.start_distance as i32
    ));
    for (suffix, d) in [("start", 0), ("mid", mid), ("late", late)] {
        text.push_str(&format!("D+{d} shot {stage}_{suffix}\n"));
        shots.push((format!("{stage}_{suffix}"), d));
    }
    text.push_str(&format!("D+{} exit\n{exit_frame} exit\n", late + 1));
    KillScript {
        stage,
        ai,
        text,
        shots,
        exit_frame,
    }
}

/// What the hook logged about one kill.
#[derive(Debug, Default, PartialEq)]
struct KillLog {
    release: Option<u32>,
    not_found: Option<String>,
    death: Option<u32>,
    /// `(frame, body, killer, killer scale)`.
    poses: Vec<(u32, Pose, Pose, f32)>,
}

fn parse_log(log: &str) -> KillLog {
    let mut k = KillLog::default();
    for line in log.lines() {
        let w: Vec<&str> = line.split_whitespace().collect();
        let frame = w.get(1).and_then(|f| f.parse().ok());
        match (w.first(), w.get(2), frame) {
            (Some(&"frame"), Some(&"release"), Some(f)) if w.get(5) == Some(&"index") => {
                k.release = Some(f)
            }
            (Some(&"frame"), Some(&"release"), _) => k.not_found = Some(w[2..].join(" ")),
            (Some(&"frame"), Some(&"death"), Some(f)) => k.death = Some(f),
            (Some(&"frame"), Some(&"pose"), Some(f)) if w.len() >= 15 => {
                let n: Vec<f32> = w[3..15].iter().filter_map(|v| v.parse().ok()).collect();
                if n.len() == 12 {
                    let pose = |o: usize| Pose {
                        phase: n[o + 1] as usize,
                        ftime: n[o + 2] as i32,
                        at: [n[o + 3], n[o + 4]],
                    };
                    k.poses.push((f, pose(0), pose(6), n[11] / 1000.0));
                }
            }
            _ => {}
        }
    }
    k
}

/// One kill, judged as our engine judges its own.
struct Judged {
    passed: bool,
    why: String,
    events: Vec<Value>,
    /// `kills_detail` entry (`kill_parity`), when the kill happened.
    report: Option<Value>,
}

fn judge(o: &Original, k: &KillPlan, s: &KillScript, log: &KillLog) -> Judged {
    let mut events = Vec::new();
    let at = log.death.unwrap_or(0);
    let mut verify = |name: &str, ok: bool, detail: String| {
        events.push(event(at, "verify", &s.stage, name, Some(ok), &detail));
        (ok, format!("{name}: {detail}"))
    };
    let (Some(release), Some(death)) = (log.release, log.death) else {
        let why = match (&log.not_found, log.release) {
            (Some(n), _) => format!("the original placed no such animal ({n})"),
            (None, None) => "the animal was not released".into(),
            (None, Some(_)) => "timeout: no kill".into(),
        };
        let (_, why) = verify("killed_by", false, why);
        return Judged {
            passed: false,
            why,
            events,
            report: None,
        };
    };
    let hunter = o.game.species.iter().find(|sp| sp.info.ai == ai::HUNTER);
    let size = o
        .game
        .species
        .iter()
        .find(|sp| sp.info.ai == s.ai)
        .map_or(0.0, |sp| sp.size);
    let scale = log.poses.first().map_or(1.0, |p| p.3);
    let frames = KillPlan {
        min_moving_ticks: k.min_moving_ticks / TICKS_PER_FRAME,
        ..k.clone()
    };
    let mut w = KillWatch::new(0, 0, death, KillWatch::reach_for(size, scale, &frames));
    for (_, b, kp, _) in &log.poses {
        let clip = hunter.map_or(Err("no hunter model".into()), |h| {
            hunter_clip(&h.ani_time, b.phase)
        });
        w.push(*b, *kp, clip);
    }
    let mut first = None;
    let mut all = true;
    let (ok, why) = verify(
        "killed_by",
        true,
        format!(
            "{} frames after release, body clip {:?}",
            death - release,
            w.body_clips.first()
        ),
    );
    all &= ok;
    first.get_or_insert(why);
    for (name, ok, detail) in w.verdicts(&frames) {
        let (ok, why) = verify(name, ok, format!("{detail} (frames of {FRAME_MS} ms)"));
        if !ok && all {
            first = Some(why);
        }
        all &= ok;
    }
    let report = w.report(&s.stage, (death - release) * FRAME_MS);
    Judged {
        passed: all,
        why: if all {
            String::new()
        } else {
            first.unwrap_or_default()
        },
        events,
        report: Some(crate::kill_parity::report_json(&report)),
    }
}

/// Runs every killer's hunt `repeat` times into `dir`; returns whether
/// every kill passed.
pub fn run(o: &Original, dir: &Path, k: &KillPlan, area: &str) -> Result<bool> {
    let weapons = o.game.weapon_names();
    let game_dir = wine::game_copy(o.game_dir, o.work, &o.game.content_hash)?;
    let prefix = wine::prefix(o.work)?;
    let exe = wine::find_ci(&game_dir, "v_soft.ren")
        .context("no v_soft.ren (the software-rendered hunt) in the game folder")?;
    let addrs = Addrs::scan(&std::fs::read(&exe)?)
        .with_context(|| format!("finding the hunt's globals in {}", exe.display()))?;
    let shots_dir = dir.join("screenshots");
    std::fs::create_dir_all(&shots_dir)?;
    let warm = (o.scenario.warmup_ticks / TICKS_PER_FRAME).max(1);

    let mut log_all = format!("globals: {addrs:#x?}\n");
    let (mut stages, mut events, mut checkpoints) = (Vec::new(), Vec::new(), Vec::new());
    let (mut identical, mut timeouts, mut passed_kills) = (true, 0, 0);
    let mut first_args = String::new();
    let mut details = Vec::new();
    for (n, r) in o.scenario.species.iter().enumerate() {
        let SpeciesRef::Ai(a) = r else {
            bail!("the original's menu takes hunt animals by AI number, not {r:?}");
        };
        let name = o
            .game
            .species
            .iter()
            .find(|sp| sp.info.ai == *a)
            .map_or_else(|| format!("ai {a}"), |sp| sp.info.name.clone());
        let mut one = o.scenario.clone();
        one.species = vec![r.clone()];
        let args = script::command_line(area, &one, weapons.len())?;
        if n == 0 {
            first_args = args.clone();
        }
        let s = kill_script(&addrs, k, warm, n, *a, &name);
        let script_path = dir.join(format!("original-script-{}.txt", s.stage));
        std::fs::write(&script_path, &s.text)?;
        let mut runs: Vec<(Vec<String>, KillLog)> = Vec::new();
        for rep in 0..o.repeat.max(1) {
            for e in std::fs::read_dir(&game_dir)?.flatten() {
                let f = e.file_name().to_string_lossy().to_ascii_lowercase();
                if f.ends_with(".bmp") || f == "c2hook.log" {
                    std::fs::remove_file(e.path())?;
                }
            }
            let mut save = c2_core::profile::new_player("regress", 0, 5000);
            save.options.res = 4;
            std::fs::write(game_dir.join("trophy00.sav"), c2_formats::sav::write(&save))?;
            let code = wine::run(&wine::Launch {
                prefix: &prefix,
                hook_dir: o.hook_dir,
                game_dir: &game_dir,
                exe: &exe,
                args: &args,
                script: &script_path,
                exit_frame: s.exit_frame,
                timeout: Duration::from_secs(300),
            })?;
            timeouts += usize::from(code.is_none());
            let hook_log = std::fs::read_to_string(game_dir.join("c2hook.log")).unwrap_or_default();
            log_all.push_str(&format!(
                "--- {} run {} (exit {code:?})\n{hook_log}",
                s.stage,
                rep + 1
            ));
            let hashes = s
                .shots
                .iter()
                .map(|(f, _)| sha_file(&game_dir.join(format!("{f}.bmp"))))
                .collect();
            if rep == 0 {
                for (f, _) in &s.shots {
                    if let Ok(img) = load_bmp(&game_dir.join(format!("{f}.bmp"))) {
                        let png = crate::image_diff::encode_rgb(img.width, img.height, &img.rgb)?;
                        std::fs::write(shots_dir.join(format!("{f}.png")), png)?;
                    }
                }
                if n == 0 {
                    let warm_ok = load_bmp(&game_dir.join("warmup.bmp"))
                        .is_ok_and(|w| (w.width, w.height) == (800, 600));
                    let why = if warm_ok {
                        ""
                    } else {
                        "no 800x600 warm-up picture"
                    };
                    stages.push(stage(
                        "warmup",
                        if warm_ok { "passed" } else { "failed" },
                        why.into(),
                        warm,
                    ));
                }
            }
            runs.push((hashes, parse_log(&hook_log)));
        }
        identical &= runs.iter().all(|r| r == &runs[0]);
        let log = &runs[0].1;
        let j = judge(o, k, &s, log);
        let (ok, why) = (j.passed, j.why);
        passed_kills += usize::from(ok);
        events.extend(j.events);
        details.extend(j.report);
        let end = log
            .death
            .map_or(s.exit_frame, |d| d + s.shots.last().map_or(0, |x| x.1));
        stages.push(stage(
            &s.stage,
            if ok { "passed" } else { "failed" },
            why,
            end,
        ));
        for ((f, d), h) in s.shots.iter().zip(&runs[0].0) {
            let frame = if f == "warmup" {
                *d
            } else {
                log.death.map_or(0, |x| x + d)
            };
            checkpoints.push(json!({ "name": f, "frame": frame, "screenshot_sha256": h }));
        }
    }
    for st in &stages {
        events.push(event(
            st["end_tick"].as_u64().unwrap_or(0) as u32,
            "stage_end",
            st["name"].as_str().unwrap_or(""),
            st["status"].as_str().unwrap_or(""),
            Some(st["status"] != "failed"),
            st["reason"].as_str().unwrap_or(""),
        ));
    }
    let count = |key: &str| stages.iter().filter(|st| st["status"] == key).count();
    let expected = o.scenario.species.len();
    let failed = count("failed") > 0 || (o.repeat > 1 && !identical) || passed_kills != expected;
    let why_none = "the original's simulation is not timed; its clock is virtual (20 ms a frame)";
    let metrics = json!({
        "result": if failed { "failed" } else { "passed" },
        "engine": "original",
        "functional": {
            "map": o.game.area_name,
            "animals_expected": expected,
            "animals_placed": unavailable("the original places its own animals; each hunt's target is released"),
            "animals_end": unavailable("not read"),
            "weapon_registry": o.game.weapons.len(),
            "weapon_registry_expected": o.def.weapons,
            "weapons_fired_once": 0,
            "weapons_to_fire": 0,
            "kills": { "expected": expected, "ran": expected, "passed": passed_kills },
            "kills_detail": details,
            "stages": { "passed": count("passed"), "failed": count("failed"), "unsupported": 0 },
            "timeouts": timeouts,
            "panics": 0,
            "setup_error": Value::Null,
        },
        "ui": {},
        "simulation": unavailable(why_none),
        "render": unavailable(why_none),
        "memory": { "process_bytes": unavailable(why_none), "peak_bytes": unavailable(why_none) },
        "determinism": if o.repeat < 2 {
            json!({ "repeats": 1, "identical": unavailable("one run: use --repeat 2 or more") })
        } else {
            json!({ "repeats": o.repeat, "identical": identical,
                    "compared": "every screenshot byte for byte, and every logged pose" })
        },
        "checkpoints": checkpoints,
    });
    let mut man = manifest(o, &first_args, &exe, o.repeat.max(1));
    man["original"]["hook"] = json!(
        "c2hook.dll: virtual timeGetTime, scripted input, growable heap, presented-frame capture; \
         kill.c releases the killer and logs the kill"
    );
    man["original"]["command_line"] = json!("one hunt per killer: din = that animal's bit");
    write_json(&dir.join("metrics.json"), &metrics)?;
    write_json(&dir.join("manifest.json"), &man)?;
    write_jsonl(&dir.join("events.jsonl"), &events)?;
    std::fs::write(dir.join("engine.log"), log_all)?;
    Ok(!failed)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_hooks_log_is_read() {
        let log = "frame 101 release AI 18 index 13 of 27\n\
                   frame 498 death body 27 killer 13 count 28\n\
                   frame 498 pose 27 3 0 100 200 863 13 9 0 100 200 863\n\
                   frame 499 pose 27 3 20 100 200 863 13 9 20 100 200 863\n";
        let k = parse_log(log);
        assert_eq!((k.release, k.death), (Some(101), Some(498)));
        assert_eq!(k.poses.len(), 2);
        assert_eq!(
            k.poses[1].1,
            Pose {
                phase: 3,
                ftime: 20,
                at: [100.0, 200.0]
            }
        );
        assert!((k.poses[0].3 - 0.863).abs() < 1e-6);
        let none = parse_log("frame 101 release AI 19 not found (27 characters)\n");
        assert_eq!(none.release, None);
        assert!(none.not_found.unwrap().contains("not found"));
    }

    #[test]
    fn the_script_waits_for_the_death() {
        let a = Addrs {
            health: 1,
            characters: 2,
            count: 3,
            player: [4, 5, 6],
            camera_alpha: 7,
        };
        let k = KillPlan {
            start_distance: 600.0,
            timeout_ticks: 1500,
            mid_ticks: 100,
            late_ticks: 200,
            min_moving_ticks: 20,
            body_reach: 3.0,
            min_body_reach: 1024.0,
        };
        let s = kill_script(&a, &k, 100, 0, 18, "T-Rex");
        assert_eq!(s.stage, "kill_01_t_rex");
        assert!(s
            .text
            .contains("100 shot warmup\n101 mark kill_01_t_rex\n101 release 18 600\n"));
        assert!(s
            .text
            .contains("D+0 shot kill_01_t_rex_start\nD+50 shot kill_01_t_rex_mid\nD+150 shot"));
        assert!(s.text.contains("D+151 exit\n"));
        assert_eq!(s.exit_frame, 101 + 750 + 150 + 10);
        let second = kill_script(&a, &k, 100, 1, 13, "Allosaurus");
        assert!(!second.text.contains("warmup"));
    }
}
