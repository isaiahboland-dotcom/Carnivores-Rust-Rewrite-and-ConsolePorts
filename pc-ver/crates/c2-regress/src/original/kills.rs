//! The kill script in the original engine (`run --engine original` with
//! `kill_animations.toml`): one hunt per killer. The hook sets the animal
//! on the hunter, notices his death (`MyHealth` reaching 0) and logs the
//! body and the killer every frame after it (`original/kill.c`). The
//! globals come from the executable's own code (`addrs`). The checks are
//! our engine's (`c2_core::scenario::KillWatch`), on those logged poses.

use std::path::Path;
use std::time::Duration;

use anyhow::{bail, Context, Result};
use c2_core::dino::ai;
use c2_core::scenario::{hunter_clip, KillPlan, KillWatch, Pose, SpeciesRef};
use serde_json::{json, Value};

use super::addrs::Addrs;
use super::checks::load_bmp;
